import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

import sharp from 'sharp'

/**
 * PLACEHOLDER-quality launch assets, derived — never drawn by hand — from the two sources
 * the product already trusts: the pergola mark in `docs/index.html` (read-only; this
 * script embeds the same paths) and the `@theme` palette via the generated mobile tokens.
 * Real brand art is a user decision (13.1); until it exists, these keep every pixel
 * traceable to a token so nothing here invents a colour.
 *
 * Outputs (committed, regenerable): mobile/assets/icon.png (1024), adaptive-icon.png
 * (1024, transparent, Android safe-zone padded), splash-icon.png (512, transparent).
 */

const tokens = JSON.parse(
  readFileSync(join(process.cwd(), 'mobile', 'src', 'theme', 'tokens.json'), 'utf8'),
)
const navy = tokens['color-primary']
const amber = tokens['color-on-tertiary-container']

// The mark from docs/index.html, verbatim: a rounded square and the pergola frame.
const mark = (size, { background, pad }) => `
<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 32 32">
  ${background ? `<rect width="32" height="32" rx="6" fill="${navy}"/>` : ''}
  <g transform="translate(${pad} ${pad}) scale(${(32 - 2 * pad) / 32})">
    <path d="M6 11h20M6 11v14M26 11v14M11 11v14M16 11v14M21 11v14"
      stroke="${amber}" stroke-width="2" stroke-linecap="round" fill="none"/>
  </g>
</svg>`

const out = join(process.cwd(), 'mobile', 'assets')
mkdirSync(out, { recursive: true })

const render = async (svg, size, file) => {
  await sharp(Buffer.from(svg)).resize(size, size).png().toFile(join(out, file))
  console.log(`generate-mobile-brand: ${file} (${size}px)`)
}

await render(mark(1024, { background: true, pad: 0 }), 1024, 'icon.png')
// Android crops adaptive icons to a circle of ~66/108 of the canvas: pad the strokes in.
await render(mark(1024, { background: false, pad: 7 }), 1024, 'adaptive-icon.png')
await render(mark(512, { background: false, pad: 2 }), 512, 'splash-icon.png')

writeFileSync(
  join(out, 'README.md'),
  [
    '# Placeholder launch assets',
    '',
    'Generated by `node scripts/generate-mobile-brand.mjs` from the pergola mark in',
    '`docs/index.html` and the parity-tested token palette. **Placeholder quality by',
    'declaration**: real brand art is a user decision (Phase 13.1), and nothing here may',
    'be mistaken for it. Regenerate rather than edit.',
    '',
  ].join('\n'),
)
console.log('generate-mobile-brand: README written')
